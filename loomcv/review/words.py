"""The applications page's sentences: pure functions that turn the
engine's records into the words the page prints.

No file is read or written here and no model is called; no UI library is imported. The page
(`loomcv/ui/review.py`) lays these out and decides nothing. What the user never sees from here: a
letter grade, a percentage, an id rule, a requirement kind token, a `pages=` counter line.
"""

from __future__ import annotations

import re
import unicodedata
from collections.abc import Collection, Sequence
from datetime import date

from pydantic import BaseModel, ConfigDict

from loomcv.application import InvalidAppId, Status
from loomcv.draft.verdict import (
    compute_verdict,
    missing_sentence,
    name_list,
    part_groups,
    short,
)
from loomcv.retrieve.rank import Candidate, MatchPayload
from loomcv.retrieve.search import JobRow
from loomcv.review.doc import ReviewDoc, coverage_of, edited_bullets
from loomcv.review.store import ListEntry, stage_label

# The verdict letters in the user's words; the thresholds stay `verdict.py`'s.
FIT_WORDS = {"A": "Good fit", "B": "Good fit", "C": "Partial fit", "D": "Weak fit"}
COVERS_CUT = 60
NAME_NEEDED = "Give this application a name"
NO_REQUIREMENTS = "We couldn't tell — this posting lists no requirements we could read."
# The note under the verdict card — the reading is a model's,
# edits change the PDF but never the rating; a new assessment is a new application.
CARD_NOTE = (
    "These results are generated by AI and may contain mistakes — treat them as a guide, not a "
    "final judgment. You can keep editing your résumé below; the PDF is made from your edited "
    "version. Editing does not change the fit rating or this summary. To get a new assessment, "
    "start a new application with this posting."
)
_BASE_ID = "application"  # the id of a name with letters but none that fold to ASCII
_KINDS = ("must", "responsibility", "nice")
_KIND_LABEL = re.compile(r"^(?P<text>.*) \((?:" + "|".join(_KINDS) + r")\)$", re.DOTALL)
_MONTHS = ("Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec")


def _count(n: int, noun: str) -> str:
    return f"{n} {noun}" if n == 1 else f"{n} {noun}s"


# ------------------------------------------------------------------ the verdict


class VerdictWords(BaseModel):
    model_config = ConfigDict(frozen=True)

    fit: str | None  # None when the posting has no required item
    headline: str
    matches: str | None
    close: list[str]  # the required lines in the close bin, payload order, their texts
    uncovered: list[str]  # one sentence per required line graded none, one per missing part
    nice: str | None


def _uncovered_sentence(text: str, listed_under: Sequence[str], in_skills: bool) -> str:
    text = text.rstrip().rstrip(".")  # the requirement's own final period, before the dash
    jobs = "; ".join(listed_under)
    if in_skills and jobs:
        return (
            f"{text} — you list it under your skills and at {jobs}, but no bullet shows it; "
            "add one in My profile"
        )
    if in_skills:
        return (
            f"{text} — you list it under your skills, but no bullet shows it; add one in My profile"
        )
    if jobs:
        return f"{text} — listed at {jobs}, but no bullet shows it"
    return f"{text} — no bullet in your profile backs this up."


def verdict_words(payload: MatchPayload, rows: Sequence[JobRow] = ()) -> VerdictWords:
    """The verdict card: the fit in words from the letter, the three counts
    in plain words, the close ones by name, one sentence per required item or named part with no
    evidence, the nice-to-have count."""
    verdict = compute_verdict(payload, rows)
    if verdict.letter is None:
        return VerdictWords(
            fit=None, headline=NO_REQUIREMENTS, matches=None, close=[], uncovered=[], nice=None
        )
    fit = FIT_WORDS[verdict.letter]
    things = "thing" if verdict.must_total == 1 else "things"
    headline = (
        f"{fit} — this posting requires {verdict.must_total} {things}. Your profile clearly "
        f"shows {verdict.direct} and shows something similar for {verdict.close}."
    )
    missing = verdict.uncovered + verdict.missing_parts
    if missing:
        headline += " " + missing_sentence(missing, "your profile")
    close = list(verdict.close_lines)
    direct = f"{verdict.direct} clearly shown"
    if close:
        them = "it" if len(close) == 1 else "those"
        matches = (
            f"{direct}; {len(close)} only something similar (expect interview questions on "
            f"{them}): " + "; ".join(short(text) for text in close)
        )
    else:
        matches = direct + "."
    groups = dict(part_groups(verdict))
    uncovered: list[str] = []
    seen: set[str] = set()
    for item in verdict.not_covered:
        if item.part is None:
            uncovered.append(_uncovered_sentence(item.text, item.listed_under, item.in_skills))
        elif item.text not in seen:
            seen.add(item.text)
            parts = groups[item.text]
            this, it = ("this", "it") if len(parts) == 1 else ("these", "them")
            uncovered.append(
                f"{name_list(parts)} — no bullet in your profile backs {this} up. The posting "
                f'asks for {it} here: "{short(item.text)}"'
            )
    nice = (
        f"Nice-to-haves your profile shows: {verdict.nice_covered} of {verdict.nice_total}."
        if verdict.nice_total
        else None
    )
    return VerdictWords(
        fit=fit, headline=headline, matches=matches, close=close, uncovered=uncovered, nice=nice
    )


def report_body(report_text: str) -> str:
    """`match_report.md` from its section 1 on when a section 0 precedes it (the card is section
    0's reading); any other text unchanged."""
    position = 0
    seen_zero = False
    for line in report_text.splitlines(keepends=True):
        if line.startswith("## 0"):
            seen_zero = True
        elif seen_zero and line.startswith("## 1"):
            return report_text[position:]
        position += len(line)
    return report_text


# ------------------------------------------------------------------ the bullets


def covers_words(labels: Sequence[str], *, cut: int = COVERS_CUT) -> list[str]:
    """`coverage_of`'s labels in the posting's own words: the kind token dropped, a text over `cut`
    characters cut with `…`; order and duplicates kept."""
    result: list[str] = []
    for label in labels:
        found = _KIND_LABEL.match(label)
        text = found.group("text") if found else label
        result.append(text if len(text) <= cut else text[:cut] + "…")
    return result


class RowWords(BaseModel):
    model_config = ConfigDict(frozen=True)

    bullet_id: str
    text: str
    covers: list[str]
    edited: bool  # differs from the vault's wording → "restore the draft's wording"


def job_rows(
    doc: ReviewDoc, job_id: str, payload: MatchPayload, candidates: Sequence[Candidate]
) -> list[RowWords]:
    """One job's bullets as the page prints them, in document order."""
    for job in doc.jobs:
        if job.job_id == job_id:
            break
    else:
        raise ValueError(f"unknown job {job_id}")
    covered = coverage_of(doc, payload, candidates)
    edited = edited_bullets(doc, candidates)
    return [
        RowWords(
            bullet_id=b.bullet_id,
            text=b.text,
            covers=covers_words(covered.get(b.bullet_id, [])),
            edited=b.bullet_id in edited,
        )
        for b in job.bullets
    ]


# ------------------------------------------------------------------ the id


def app_id_from_name(name: str, taken: Collection[str], *, today: date | None = None) -> str:
    """The application id from the name the user typed: lower-case, accents
    folded, every run of characters outside `[a-z0-9._-]` one `-`, `._-` trimmed at both ends. A
    name with a letter or digit but nothing that folds to ASCII gets the base `application`; a name
    with neither is refused. On a collision with `taken` (casefolded): `-YYYYMMDD`, then
    `-YYYYMMDD-2`, `-3`, …"""
    folded = unicodedata.normalize("NFKD", name.lower())
    folded = "".join(ch for ch in folded if not unicodedata.combining(ch))
    slug = re.sub(r"[^a-z0-9._-]+", "-", folded)
    slug = re.sub(r"-{2,}", "-", slug).strip("._-")
    if not slug:
        if not any(ch.isalnum() for ch in name):
            raise InvalidAppId(NAME_NEEDED)
        slug = _BASE_ID
    used = {t.casefold() for t in taken}
    if slug not in used:
        return slug
    stamp = (today or date.today()).strftime("%Y%m%d")
    candidate, n = f"{slug}-{stamp}", 2
    while candidate in used:
        candidate, n = f"{slug}-{stamp}-{n}", n + 1
    return candidate


# ------------------------------------------------------------------ the list


class EntryWords(BaseModel):
    model_config = ConfigDict(frozen=True)

    title: str
    sub: str  # "<name or id> · started Nov 8"
    stage: str
    done: bool


def entry_words(entry: ListEntry) -> EntryWords:
    """One entry of the left list in three lines."""
    sub = entry.name or entry.app_id
    if entry.started is not None:
        sub = f"{sub} · started {_MONTHS[entry.started.month - 1]} {entry.started.day}"
    return EntryWords(
        title=entry.title,
        sub=sub,
        stage=stage_label(entry.status),
        done=entry.status.status == "done",
    )


def tally_words(entries: Sequence[ListEntry]) -> str:
    """The bar's line on the New pane: how many applications, how many with a PDF."""
    done = sum(1 for e in entries if e.status.status == "done")
    return f"{len(entries)} so far · {done} PDF ready"


# ------------------------------------------------------------------ the PDF


class PdfWords(BaseModel):
    model_config = ConfigDict(frozen=True)

    line: str
    ok: bool  # within the limit → green; over → amber
    notes: list[str]  # one per typst warning
    pdf: str | None


def pdf_words(status: Status) -> PdfWords | None:
    """The PDF line in words; `None` until there is a PDF on record."""
    if status.status != "done" or not status.final_pdf:
        return None
    pages = _count(status.pages, "page") if status.pages is not None else None
    ok = not status.over_limit
    if ok:
        line = f"PDF ready — {pages}, within the limit." if pages else "PDF ready."
    else:
        line = (
            f"The PDF runs to {pages}; the limit is {status.page_limit}. "
            "Remove or shorten a few bullets and make it again."
        )
    notes = [f"Note from the typesetter: {warning}" for warning in status.typst_warnings]
    return PdfWords(line=line, ok=ok, notes=notes, pdf=status.final_pdf)


def built_words(status: Status) -> str:
    """The toast after a Build: the placed-bullet count when the status carries it."""
    bullets = status.counts.get("bullets")
    if bullets is None:
        return "Draft ready"
    return f"Draft ready — {_count(bullets, 'bullet')} picked"
