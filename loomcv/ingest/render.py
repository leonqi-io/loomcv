"""The draft vault: its public models and the deterministic v3 renderer.

Leaf layer of `loomcv.ingest` (`render` ← `keywords` ← `extract`): the draft models the
renderer and the completion loop read, the package's error, `render_vault` (pure, byte-stable,
every bullet `{id, status, updated}` — `draft` unless the completion loop confirmed it —,
no leading `[Tag]` ever written, an optional vault-level `Skills` line under the H1) and
`check_rendered`, the in-module acceptance: the strict v3 parser over the rendered text with
drafts included — with the default `include_draft=False` every count would be 0.
"""

from __future__ import annotations

from datetime import date
from typing import Literal

from pydantic import BaseModel

from loomcv.sync.parse_assets import ParseIssue, SkillGroup, VaultHeader, parse_star_vault


class IngestError(Exception):
    """The generation path failed: a transport error, or no valid reply after one retry.

    `raws` holds every reply received so far, in call order."""

    def __init__(self, message: str, raws: list[str] | None = None) -> None:
        super().__init__(message)
        self.raws = list(raws or [])


class DraftBullet(BaseModel):
    id: str
    text: str
    project: str | None = None
    keywords: list[str] = []
    # L1 writes every bullet `draft` stamped today; L2 (`loomcv.complete`) renders confirmed ones.
    status: Literal["draft", "confirmed"] = "draft"
    updated: str | None = None  # ISO date; None = the render's stamp


class DraftJob(BaseModel):
    name: str
    employer: str | None = None
    title: str | None = None
    date_from: str
    date_to: str
    defaults: list[str] = []
    bullets: list[DraftBullet]


class DraftVault(BaseModel):
    header: VaultHeader = VaultHeader()  # the vault-level header lines
    skills: list[str] = []  # the unnamed group: the `Skills` line's own items
    skill_groups: list[SkillGroup] = []  # the named groups, printed as indented lines
    jobs: list[DraftJob]


def render_vault(draft: DraftVault, *, today: date, heading: str | None = None) -> str:
    """The v3 vault text: the H1, the vault-level lines directly under it in the fixed order
    `Name` / `Headline` / `Contact` / `Summary` / `Education` / `Skills` (+ its group lines),
    absent lines absent, then per job (in draft order — the parser sorts by date) the header
    lines in the fixed order, absent lines absent, one blank line between jobs."""
    stamp = today.isoformat()
    title = heading or f"Draft STAR Vault — generated by pipeline ingest, {stamp}"
    lines = [f"# {title}"]
    header = draft.header
    for key, value in (
        ("Name", header.name),
        ("Headline", header.headline),
        ("Contact", "; ".join(header.contact)),
        ("Summary", header.summary),
        ("Education", "; ".join(header.education)),
    ):
        if value:
            lines.append(f"* **{key}**: {value}")
    if draft.skills:
        lines.append(f"* **Skills**: {'; '.join(draft.skills)}")
    elif draft.skill_groups:
        lines.append("* **Skills**:")
    for group in draft.skill_groups:
        lines.append(f"  * **{group.name}**: {'; '.join(group.items)}")
    for job in draft.jobs:
        lines.append("")
        lines.append(f"## [Job] {job.name}")
        if job.employer:
            lines.append(f"* **Employer**: {job.employer}")
        if job.title:
            lines.append(f"* **Title**: {job.title}")
        lines.append(f"* **From**: {job.date_from}")
        lines.append(f"* **To**: {job.date_to}")
        if job.defaults:
            lines.append(f"* **Defaults**: {'; '.join(job.defaults)}")
        lines.append("* **Bullets**:")
        for bullet in job.bullets:
            block = f"id: {bullet.id}, status: {bullet.status}, updated: {bullet.updated or stamp}"
            lines.append(f"  - {bullet.text} {{{block}}}")
            if bullet.project:
                lines.append(f"    * **Project**: {bullet.project}")
            if bullet.keywords:
                lines.append(f"    * **Keywords**: {'; '.join(bullet.keywords)}")
    return "\n".join(lines) + "\n"


def check_rendered(rendered: str) -> list[ParseIssue]:
    """Every issue the strict parser reports on the rendered draft, drafts included."""
    return parse_star_vault(rendered, include_draft=True).issues
