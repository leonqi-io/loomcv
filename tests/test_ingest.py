def _resume_jobs(resume: str) -> dict[str, tuple[list[str], list[str]]]:
    """Job heading → (Technologies items, project sub-headings), from the résumé's own text."""
    jobs: dict[str, tuple[list[str], list[str]]] = {}
    current: str | None = None
    for line in resume.splitlines():
        if line.startswith("## "):
            current = None
        elif line.startswith("### "):
            current = line[4:].strip()
            jobs[current] = ([], [])
        elif current and line.startswith("Technologies:"):
            jobs[current][0].extend(i.strip() for i in line.split(":", 1)[1].split(","))
        elif current and (m := re.fullmatch(r"\*\*(.+)\*\*", line.strip())):
            jobs[current][1].append(m.group(1))
    return jobs


def _t1_project_tech(prompt: str) -> dict[str, set[str]]:
    """`### Project n: <name>` → its "Technologies used somewhere in this project" items."""
    tech: dict[str, set[str]] = {}
    name: str | None = None
    for line in prompt.splitlines():
        if m := re.match(r"^### Project \d+: (.+)$", line):
            name = m.group(1).strip()
        elif name and line.startswith("Technologies used somewhere in this project:"):
            tech[name] = {i.strip() for i in line.split(":", 1)[1].split(";")}
    return tech


def test_fixture_pair_is_verbatim_and_survives_post_validation():
    # I-11 — guards the fixture pair, not the model. The third block (the 42
    # bullets through `ingest_resume`) is what makes this test fail when the pair drifts.
    resume = RESUME_42.read_text(encoding="utf-8")
    vault = parse_star_vault(VAULT_42.read_text(encoding="utf-8"))
    assert vault.errors() == []
    bullets = [b for j in vault.jobs for b in j.bullets]
    assert len(bullets) == 42

    # 1. Every vault bullet text is a substring of the whitespace-normalised résumé.
    norm_resume = _norm(resume)
    for b in bullets:
        assert _norm(b.text) in norm_resume, b.bullet_id

    # 2. Every Technologies item of each résumé job is in its projects' T1 tech lines.
    project_tech = _t1_project_tech(T1_PROMPT.read_text(encoding="utf-8"))
    resume_jobs = _resume_jobs(resume)
    assert len(resume_jobs) == 3
    for heading, (technologies, projects) in resume_jobs.items():
        assert technologies, heading
        assert projects, heading
        allowed = set().union(*(project_tech[p] for p in projects))
        for item in technologies:
            assert item in allowed, (heading, item)

    # 3. The 42 bullets, returned verbatim by a fake structure reply (valid dates, no
    # defaults), all survive L1's own post-validation against the résumé: no drop, no
    # warning, a strict-clean draft.
    structure = {
        "jobs": [
            {
                "employer": j.employer,
                "title": j.title,
                "date_from": j.date_from,
                "date_to": j.date_to,
                "defaults": [],
                "bullets": [{"text": b.text, "project": b.project} for b in j.bullets],
            }
            for j in vault.jobs
        ]
    }
    result = _ingest(_scripted(structure), resume=resume)
    assert result.warnings == []
    assert sum(len(j.bullets) for j in result.draft.jobs) == 42
    assert [b.text for j in result.draft.jobs for b in j.bullets] == [b.text for b in bullets]
    assert [i for i in result.parse_issues if i.severity == "error"] == []


