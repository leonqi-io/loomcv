def _claims_structure_reply() -> dict:
    """The canned structure reply for `synthetic_resume_claims.md`: the three jobs with their
    bullets taken verbatim from the expected vault, the competencies from the résumé's own
    "Core competencies" paragraph (a vault-level list, assigned to no job)."""
    expected = parse_star_vault(CLAIMS_VAULT.read_text(encoding="utf-8"), include_draft=True)
    resume = RESUME_CLAIMS.read_text(encoding="utf-8")
    competencies = resume.split("## Core competencies", 1)[1].split("##", 1)[0].strip()
    return {
        "skills": [item.strip() for item in competencies.split(",")],
        "jobs": [
            {
                "employer": job.employer,
                "title": job.title,
                "date_from": job.date_from,
                "date_to": job.date_to,
                "defaults": [],
                "bullets": [{"text": b.text, "project": None} for b in job.bullets],
            }
            for job in sorted(expected.jobs, key=lambda j: j.line_no)
        ],
    }


