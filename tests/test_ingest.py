def test_post_validation_drops_and_marks_never_adds():
    # I-4 (+ cases (a′) and (g))

    # (a) one word changed → not in source.
    changed = "Reduced checkout errors on the public website by 40%."
    result, _ = _auto(_structure(job1={"bullets": [{"text": B1}, {"text": changed}]}))
    assert result.warnings == [f"dropped bullet '{changed[:40]}' (text not in source)"]
    assert [b.text for b in result.draft.jobs[0].bullets] == [B1]

    # (b) 99% where the résumé says 40% → the same rule.
    inflated = B2.replace("40%", "99%")
    result, _ = _auto(_structure(job1={"bullets": [{"text": B1}, {"text": inflated}]}))
    assert result.warnings == [f"dropped bullet '{inflated[:40]}' (text not in source)"]

    # (c) a brace in the text → dropped (the grammar reserves {}).
    braced = "Cut the p95 latency {fast} of the order API."
    result, _ = _auto(_structure(job1={"bullets": [{"text": B1}, {"text": braced}]}))
    assert result.warnings == [
        f"dropped bullet '{braced[:40]}' (brace in text; the vault grammar reserves {{}})"
    ]

    # (d) deleted with the keyword call: the ';' rule on keywords is S-3.

    # (e) / (f) unparseable dates → 0000 with a warning; (g) present is kept.
    result, _ = _auto(_structure(job1={"date_from": "March 2021", "date_to": "2025-13"}))
    assert result.warnings == [
        f"unparsed From 'March 2021' for job '{JOB1}' (marked 0000)",
        f"unparsed To '2025-13' for job '{JOB1}' (marked 0000)",
    ]
    assert (result.draft.jobs[0].date_from, result.draft.jobs[0].date_to) == ("0000", "0000")
    result, _ = _auto(STRUCTURE_REPLY)
    assert result.draft.jobs[0].date_to == "present"
    assert result.warnings == []

    # (h) a job whose only bullet is dropped is KEPT, with no bullets.
    other = B4.replace("small", "large")
    result, _ = _auto(_structure(job2={"bullets": [{"text": other}]}))
    assert result.warnings == [f"dropped bullet '{other[:40]}' (text not in source)"]
    assert [j.name for j in result.draft.jobs] == [JOB1, "Freelance Developer"]
    assert result.draft.jobs[1].bullets == []

    # (i) the same display name three times → ordinal suffixes, one warning each.
    same = {"employer": "Acme Widgets", "title": "Platform Engineer", "bullets": [{"text": B4}]}
    result, _ = _auto({"jobs": [dict(same), dict(same), dict(same)]})
    assert [j.name for j in result.draft.jobs] == [JOB1, f"{JOB1} (2)", f"{JOB1} (3)"]
    assert result.warnings == [
        f"duplicate job name '{JOB1}' renamed to '{JOB1} (2)'",
        f"duplicate job name '{JOB1}' renamed to '{JOB1} (3)'",
    ]
    parsed = parse_star_vault(result.rendered, include_draft=True)
    assert parsed.errors() == []
    assert len(parsed.jobs) == 3

    # (j) neither employer nor title → `Job <n>` (n = reply position) and a warning.
    result, _ = _auto(_structure(job2={"employer": None, "title": None}))
    assert [j.name for j in result.draft.jobs] == [JOB1, "Job 2"]
    assert result.warnings == ["job 2 has neither employer nor title"]

    # (a′) a bullet whose text is empty after normalisation is dropped.
    result, _ = _auto(_structure(job1={"bullets": [{"text": B1}, {"text": " \n "}]}))
    assert result.warnings == ["dropped bullet '' (empty text)"]

    # (g) whitespace inside employer / title / project / list items is normalised —
    # formatting only; the mangled reply renders exactly the expected vault.
    mangled = _structure(
        job1={
            "employer": " Acme\nWidgets ",
            "title": "Platform\n  Engineer",
            "defaults": ["Python", " Django\n", "PostgreSQL"],
            "bullets": [
                {"text": B1.replace(" by moving", "\n   by moving")},
                {"text": B2},
                {"text": B3, "project": "Billing\n Revamp"},
            ],
        }
    )
    result = _ingest(_scripted(mangled))
    assert result.warnings == []
    assert result.rendered == _expected_text()


