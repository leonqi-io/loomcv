class FakeGenerationAdapter:
    """Scripted, network-free stand-in for `GenerationAdapter`."""

    def __init__(
        self, replies: list[str], *, temperature: float = 0, model_id: str = "fake-model"
    ) -> None:
        self._replies = list(replies)
        self._temperature = temperature
        self._model_id = model_id
        self.calls: list[tuple[str, str, float]] = []

    @property
    def model_id(self) -> str:
        return self._model_id

    @property
    def temperature(self) -> float:
        return self._temperature

    def complete(self, system: str, user: str, *, temperature: float) -> str:
        self.calls.append((system, user, temperature))
        return self._replies.pop(0)


def _expected_text() -> str:
    return EXPECTED_VAULT.read_text(encoding="utf-8")


def _norm(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip()


def _sha6(text: str) -> str:
    return hashlib.sha1(text.encode("utf-8")).hexdigest()[:6]


def _structure(**job_overrides) -> dict:
    """A deep copy of STRUCTURE_REPLY; `job1=` / `job2=` dicts update those jobs."""
    reply = copy.deepcopy(STRUCTURE_REPLY)
    for key, index in (("job1", 0), ("job2", 1)):
        if key in job_overrides:
            reply["jobs"][index].update(job_overrides[key])
    return reply


def _ingest(adapter, *, resume: str = SHORT_RESUME, today: date = TODAY):
    from loomcv.ingest import ingest_resume

    return ingest_resume(
        resume,
        adapter=adapter,
        today=today,
        structure_template=STRUCTURE_PROMPT,
    )


def _auto(structure: dict):
    adapter = _scripted(structure)
    return _ingest(adapter), adapter


def _scripted(*replies) -> FakeGenerationAdapter:
    return FakeGenerationAdapter([r if isinstance(r, str) else json.dumps(r) for r in replies])


