def test_one_retry_per_call_and_reply_cleaning():
    # I-5
    from loomcv.ingest import IngestError

    valid = json.dumps(STRUCTURE_REPLY)

    # Structure: invalid then valid → OK; the retry carries the suffix.
    adapter = _scripted("Sure! " + valid, valid)
    result = _ingest(adapter)
    assert result.rendered == _expected_text()
    assert len(adapter.calls) == 2
    assert "was not valid" in adapter.calls[1][1]
    assert "was not valid" not in adapter.calls[0][1]

    # Structure: two invalid → IngestError carrying both raws.
    adapter = _scripted("Sure! " + valid, "still not json")
    with pytest.raises(IngestError) as exc:
        _ingest(adapter)
    assert exc.value.raws == ["Sure! " + valid, "still not json"]
    assert len(adapter.calls) == 2

    # `null` for defaults / bullets is read as [] — no retry.
    nulls = _structure(job2={"defaults": None})
    adapter = _scripted(nulls)
    result = _ingest(adapter)
    assert len(adapter.calls) == 1
    assert result.rendered == _expected_text()
    # A job whose bullets came back null is kept, bullet-less.
    no_bullets = _structure(job2={"bullets": None})
    adapter = _scripted(no_bullets)
    result = _ingest(adapter)
    assert len(adapter.calls) == 1
    assert [j.name for j in result.draft.jobs] == [JOB1, "Freelance Developer"]
    assert result.draft.jobs[1].bullets == []

    # A ```json fence and a leading <think> block are cleaned.
    for reply in (f"```json\n{valid}\n```", f"<think>plan</think>\n{valid}"):
        adapter = _scripted(reply)
        result = _ingest(adapter)
        assert result.rendered == _expected_text()
        assert len(adapter.calls) == 1


