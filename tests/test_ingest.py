def test_ids_are_sha1_of_the_normalised_text_unique_per_job():
    # I-8
    from loomcv.ingest import assign_ids

    assert assign_ids([B1, "a  b\n c"]) == [_sha6(B1), _sha6("a b c")]

    first, second = assign_ids([B1, B1])
    assert first == _sha6(B1)
    assert second == _sha6(B1 + "\n2")
    assert first != second
    for ident in (first, second):
        assert re.fullmatch(r"[a-z0-9]{4,8}", ident)

    # Unique per job is the rule: the same text in two jobs gets the same id.
    assert assign_ids([B4]) == assign_ids([B4]) == [_sha6(B4)]

    base = _ingest(_scripted(STRUCTURE_REPLY))
    assert _ids(base) == ["395f62", "e8eb3d", "b37b54", "174378"]
    varied = _structure(
        job1={
            "date_from": "2019-01",
            "date_to": "2020-12",
            "defaults": ["Go"],
            "bullets": [
                {"text": B1, "project": "Latency Work"},
                {"text": B2},
                {"text": B3},
            ],
        }
    )
    assert _ids(_ingest(_scripted(varied))) == _ids(base)


